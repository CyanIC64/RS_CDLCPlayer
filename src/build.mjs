// Builds V1.1's web/ scripts from the sources in this folder.
//   node build.mjs                 (esbuild must be resolvable, or set ESBUILD to its path)
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const esbuild = require(process.env.ESBUILD || "esbuild");
const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.argv[2] || path.join(here, "..", "deploy_ready", "V1.1", "web");
fs.mkdirSync(out, { recursive: true });

// 1. the in-page converter (fallback when a Worker cannot be started)
await esbuild.build({ entryPoints: [path.join(here, "converter.entry.js")], bundle: true, format: "iife",
                      outfile: path.join(out, "converter.js"), legalComments: "inline", logLevel: "warning" });

// 2. the worker: converter + ww2ogg in one script, wrapped as a string so the page
//    can start it from a Blob - a Worker cannot be loaded from a file:// URL.
if (fs.existsSync(path.join(here, "worker.entry.js"))) {
  const r = await esbuild.build({ entryPoints: [path.join(here, "worker.entry.js")], bundle: true, format: "iife",
                                  write: false, legalComments: "inline", logLevel: "warning" });
  // LF only: a Windows checkout (core.autocrlf) would otherwise put "\r\n" inside the string
  const ww2ogg = fs.readFileSync(path.join(here, "vendor", "ww2ogg.bundle.js"), "utf8").replace(/\r\n/g, "\n");
  const src = ww2ogg + "\n;\n" + r.outputFiles[0].text;
  fs.writeFileSync(path.join(out, "converter.worker.js"),
    "// Generated by build.mjs - the Play Song converter, run in a Web Worker.\n" +
    "// Kept as a string: the page starts it from a Blob so it also works from file://.\n" +
    "window.CDLC_WORKER_SOURCE = " + JSON.stringify(src) + ";\n");
}

// 3. note detection: the AudioWorklet processor is kept as a string (the page loads it
//    from a Blob - audioWorklet.addModule cannot load a file:// URL either), and the
//    page's side is exposed as window.PitchKit.
if (fs.existsSync(path.join(here, "detect", "pitch.entry.js"))) {
  const proc = await esbuild.build({ entryPoints: [path.join(here, "detect", "processor.entry.js")], bundle: true,
                                     format: "iife", write: false, legalComments: "inline", logLevel: "warning" });
  await esbuild.build({ entryPoints: [path.join(here, "detect", "pitch.entry.js")], bundle: true, format: "iife",
                        globalName: "PitchKit", outfile: path.join(out, "pitch.js"),
                        define: { PROCESSOR_SOURCE: JSON.stringify(proc.outputFiles[0].text) },
                        banner: { js: "// Generated by build.mjs - Play Song note detection (window.PitchKit)." },
                        legalComments: "inline", logLevel: "warning" });
}
for (const f of fs.readdirSync(out)) console.log(`${f}  ${(fs.statSync(path.join(out, f)).size / 1024).toFixed(0)} KB`);
