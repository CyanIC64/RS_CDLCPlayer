// Makes the gear library: a JSON file for each amp, cabinet, pedal and rack
// found in the tones of .psarc files, in src/amp/gear/{amps,cabinets,pedals}/,
// then gathers every file there into gear/library.js (what the bundles read).
//
//   node amp/make-gear.mjs <file.psarc | folder> ...     add the gear not in the library yet
//   node amp/make-gear.mjs --force <...>                 write every piece again (hand edits are lost)
//   node amp/make-gear.mjs                               only gather the files into library.js
//
// A new file says how each knob maps to the pedalboard; edit it to change
// what a piece of gear sounds like, then run node build.mjs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const GEAR = path.join(here, "gear");
const DIR_OF = { amp: "amps", cabinet: "cabinets", pedal: "pedals", rack: "pedals" };

/** gather every JSON file of the library into gear/library.js; returns how many */
export function writeLibrary(dir = GEAR) {
  const all = {};
  for (const sub of ["amps", "cabinets", "pedals"]) {
    const d = path.join(dir, sub);
    if (!fs.existsSync(d)) continue;
    for (const f of fs.readdirSync(d).filter((f) => f.endsWith(".json")).sort()) {
      let e;
      try { e = JSON.parse(fs.readFileSync(path.join(d, f), "utf8")); }
      catch (err) { throw new Error(`gear/${sub}/${f}: ${err.message}`); }
      if (!e || typeof e.key !== "string") throw new Error(`gear/${sub}/${f}: no "key"`);
      all[e.key] = e;
    }
  }
  const body = Object.keys(all).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(all[k])},`).join("\n");
  fs.writeFileSync(path.join(dir, "library.js"),
    "// Generated by make-gear.mjs (and build.mjs) from the JSON files beside it - edit those, not this.\n" +
    "export default {\n" + body + (body ? "\n" : "") + "};\n");
  return Object.keys(all).length;
}

/* JSON with one line per knob: easy to read and to edit by hand */
export function pretty(obj) {
  return JSON.stringify(obj, null, 2)
    .replace(/\[\s+([^[\]{}]*?)\s+\]/g, (m, inner) => "[" + inner.split(/,\s*/).join(", ") + "]")
    .replace(/\{\s+([^{}]*?)\s+\}/g, (m, inner, at) => (at === 0 ? m : "{ " + inner.split(/,\s*\n\s*/).join(", ") + " }"));
}

function psarcsIn(p) {
  const st = fs.statSync(p);
  if (st.isFile()) return /\.psarc$/i.test(p) ? [p] : [];
  return fs.readdirSync(p).flatMap((f) => psarcsIn(path.join(p, f)));
}

async function scan(files) {
  const { Psarc } = await import("../psarc.js");
  const { knobName, TYPE_OF_SLOT, cabBase } = await import("./gear.js");
  const found = new Map();                       // key -> { type, category, seen }
  for (const f of files) {
    let arc;
    try { arc = new Psarc(new Uint8Array(fs.readFileSync(f))); } catch (e) { console.warn(`${f}: ${e.message}`); continue; }
    const names = (await arc.names()).filter((n) => /manifests\/.*\.json$/i.test(n) && !/vocals/i.test(n));
    for (const n of names) {
      let j;
      try { j = JSON.parse(new TextDecoder().decode(await arc.read(n))); } catch (e) { continue; }
      for (const ent of Object.values(j.Entries || {})) {
        for (const t of (ent.Attributes && ent.Attributes.Tones) || []) {
          for (const [slot, g] of Object.entries(t.GearList || {})) {
            const type = TYPE_OF_SLOT(slot, g.Type);
            /* a cabinet's file is its enclosure's: the microphone is in the tone, not in the cabinet */
            const key = g && (g.Key || g.PedalKey) && (type === "cabinet" ? cabBase(g.Key || g.PedalKey) : g.Key || g.PedalKey);
            if (!key) continue;
            const it = found.get(key) || { type, category: g.Category || "", seen: {} };
            for (const [k, v] of Object.entries(g.KnobValues || {})) {
              const name = knobName(key, k), x = Number(v);
              if (!Number.isFinite(x)) continue;
              const r = it.seen[name];
              it.seen[name] = r ? [Math.min(r[0], x), Math.max(r[1], x)] : [x, x];
            }
            found.set(key, it);
          }
        }
      }
    }
    console.log(`${path.basename(f)}: read`);
  }
  return found;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const force = args.includes("--force");
  const files = args.filter((a) => !a.startsWith("--")).flatMap(psarcsIn);
  if (files.length) {
    const { describeGear } = await import("./gear.js");
    const found = await scan(files);
    let added = 0, kept = 0;
    for (const [key, it] of found) {
      const file = path.join(GEAR, DIR_OF[it.type], key.replace(/[^\w.-]+/g, "_") + ".json");
      if (fs.existsSync(file) && !force) { kept++; continue; }
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, pretty(describeGear(it.type, key, it.seen, { category: it.category })) + "\n");
      added++;
    }
    console.log(`gear: ${added} written, ${kept} already in the library`);
  }
  console.log(`gear/library.js: ${writeLibrary()} pieces`);
}
